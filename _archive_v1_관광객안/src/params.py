from dataclasses import dataclass, field
from typing import Any, List


@dataclass
class Param:
    value: Any
    grade: str                      # A / B / C / X
    basis: str                      # 왜 이 값인가
    source: str = ""                # 근거 데이터·문헌
    replace: str = ""               # 어떻게 하면 등급을 올릴 수 있는가
    need: str = ""                  # 담당자에게 요청할 자료
    note: str = ""
    name: str = ""


P: List[Param] = []


def reg(name, **kw):
    p = Param(name=name, **kw)
    P.append(p)
    return p


def summary():
    c = {"A": 0, "B": 0, "C": 0, "X": 0}
    for p in P:
        c[p.grade] = c.get(p.grade, 0) + 1
    return c


